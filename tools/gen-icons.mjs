// Generates crates/anyps5-launcher/src/ui/icons_table.rs from the Phosphor web CSS.
// Usage: node tools/gen-icons.mjs <path to phosphor-icons/web src/regular/style.css>
import { readFileSync, writeFileSync } from "node:fs";

const css = readFileSync(process.argv[2], "utf8");
// Phosphor names used by the launcher (docs/DESIGN.md 5.16).
const names = `squares-four dots-nine gear-six game-controller lock lock-open warning clock arrow-circle-down
check-circle arrows-clockwise arrow-clockwise hourglass play play-circle x trophy dots-three circle-dashed
hard-drive hash tag folder magnifying-glass stack caret-left caret-right caret-up caret-down minus plus
stethoscope file-text paint-brush globe sliders-horizontal wrench info palette circle-half images image wind
user-circle speaker-high music-notes discord-logo eye-slash power rectangle frame-corners app-window arrows-out-simple wave-sine keyboard
sliders gauge translate sparkle trash mouse arrows-down-up chart-line-up crosshair timer person-simple-walk
export download-simple arrow-counter-clockwise circle list hand-pointing arrows-out-cardinal camera text-aa
x-circle arrow-right check question folder-open folder-simple-dashed arrow-up arrow-down arrow-left link
github-logo floppy-disk clock-counter-clockwise users user-plus user-minus envelope-simple
paper-plane-right cloud sign-in sign-out prohibit flag key
microphone microphone-slash speaker-slash headphones
device-mobile wifi-high plug`.split(/\s+/);

const BS = String.fromCharCode(92);
const lines = [];
for (const name of names) {
  const re = new RegExp(`[.]ph-${name}:before[ \\t\\r\\n]*[{][ \\t\\r\\n]*content:[ \\t]*"[\\\\]([0-9a-f]+)"`);
  const m = css.match(re);
  if (!m) throw new Error(`icon not found: ${name}`);
  const id = name.toUpperCase().replaceAll("-", "_");
  lines.push(`    pub const ${id}: Icon = Icon('${BS}u{${m[1]}}');`);
}
writeFileSync(
  new URL("../crates/anyps5-launcher/src/ui/icons_table.rs", import.meta.url),
  `// @generated by tools/gen-icons.mjs from Phosphor Icons (MIT). Do not edit.\n// Regular and fill weights share one code point per icon.\nimpl Icon {\n${lines.join("\n")}\n}\n`,
);
console.log(`${names.length} icons`);
